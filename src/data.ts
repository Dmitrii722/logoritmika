export function interpret(total: number): { label: string; text: string } {
  if (total === 0) {
    return {
      label: 'Ожидание данных',
      text: 'Заполните диагностические таблицы выше, чтобы получить интерпретацию результатов.',
    };
  }
  if (total <= 18) {
    return {
      label: 'Выраженная поддержка',
      text: 'Требуется выраженная поддержка в развитии предпосылок речи, внимания и подражания. Рекомендуется индивидуальный подход и частое повторение материала.',
    };
  }
  if (total <= 37) {
    return {
      label: 'Навыки формируются',
      text: 'Навыки формируются, нужна системная логоритмическая практика. Ребёнок демонстрирует нестабильные, но явные достижения.',
    };
  }
  return {
    label: 'Хорошая динамика',
    text: 'Хорошая динамика развития речевых и моторных предпосылок. Ребёнок уверенно усваивает материал и готов к усложнению.',
  };
}

